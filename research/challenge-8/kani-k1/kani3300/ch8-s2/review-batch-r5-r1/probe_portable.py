#!/usr/bin/env python3
"""Reviewer assertions on bounded synthetic upload-only bytes; no real archives."""
import copy, gzip, hashlib, json, os, shutil, sys, tempfile, time
from pathlib import Path
sys.dont_write_bytecode=True
HERE=Path(__file__).resolve().parent
P=json.loads((HERE.with_name('batch-r5-r1')/'PINS.json').read_text())
sys.path.insert(0,str(Path(P['control']['worktree'])/'ch8-s1-control'))
import collect as collector
import r5_campaign as c
import r5_profile as p
import runner as r
import pack_evidence
from test_r5 import PortablePrefixTests

def sha(data):return hashlib.sha256(data).hexdigest()
def dump(name,doc):(HERE/name).write_text(json.dumps(doc,indent=2)+'\n')

def main():
    start=time.monotonic_ns()
    helper=PortablePrefixTests()
    with tempfile.TemporaryDirectory(prefix='review14-r1-portable-') as temp:
        base=Path(temp)
        out,request,rid,prefix=helper.make_pair(base)
        seal=c.sealed(out)[rid]
        upload=helper.upload_only(base,out)
        artifact=helper.archive_doc(upload)
        assert artifact['state']=='PACKAGED'
        assert set(seal['files'])<=set(artifact['files'])
        assert all(name.endswith('.json') for name in artifact['files'])
        assert seal['local_only_file_digests']
        assert all(value['scope']=='LOCAL_CAPTURE_BYTES_ONLY_NOT_UPLOADED_NOT_REQUIRED_FOR_PORTABLE_REPLAY'
                   for value in seal['local_only_file_digests'].values())
        assert not set(seal['local_only_file_digests']) & set(artifact['files'])
        # Upload-only directory, producer tree gone. No path can use its raw logs.
        shutil.rmtree(out)
        assert list(upload.iterdir())==[upload/pack_evidence.NAME]
        assert c.sealed(upload,collector.read_bytes,[rid])[rid]==seal
        assert collector.read_bytes(upload/rid/'receipt.json')==prefix
        result=collector.collect([upload],request)
        rows={row['id']:row for row in result['rows']}
        assert rows[rid]['outcome']=='RECORDED' and rows[rid]['r5_expected_match'] is True
        assert rows[p.ORDER[1]]['outcome']=='UNKNOWN'
        assert all(rows[x]['outcome']=='UNKNOWN' for x in p.ORDER[2:])
        assert all(rows[x]['status']=='DEFERRED_NOT_SELECTED' for x in p.DEFERRED)
        assert result['proof_credit']=='NONE' and result['full_inventory_complete'] is False
        members={name:{'sha256':sha(collector.read_bytes(upload/name)),
                       'bytes':len(collector.read_bytes(upload/name))} for name in seal['files']}
        def save(doc):helper.write_archive(upload,doc)
        def reseal(doc,value):
            data=json.dumps(value,sort_keys=True).encode()
            doc['files']['completed/'+rid+'.json'].update(text=data.decode(),bytes=len(data),sha256=sha(data))
        def rejected(doc):
            save(doc);states={}
            for name,operation in [('seal',lambda:c.sealed(upload,collector.read_bytes,[rid])),
                                   ('collect',lambda:collector.collect([upload],request))]:
                try:operation()
                except (c.GlobalFailure,r.RunnerError,KeyError,ValueError,TypeError) as error:
                    states[name]={'type':type(error).__name__,'message':str(error)}
                else:raise AssertionError(name+' accepted a malformed/missing/tampered sealed member')
            return states
        negatives=[]
        # Every structured member generated by this fixture (compile, binding/
        # native metadata, export, property and row/supervision bytes) is checked.
        # Diagnostic producers/decoders are separately verified byte-invariant.
        for name in seal['files']:
            doc=copy.deepcopy(artifact);del doc['files'][name]
            negatives.append({'case':'missing_structured_member','member':name,'results':rejected(doc)})
            doc=copy.deepcopy(artifact);entry=doc['files'][name]
            changed=(entry['text']+' ').encode()
            entry.update(text=changed.decode(),bytes=len(changed),sha256=sha(changed))
            negatives.append({'case':'changed_bytes_rehashed_archive_entry','member':name,'results':rejected(doc)})
        malformed=[]
        def malformed_case(label,edit):
            doc=copy.deepcopy(artifact);value=copy.deepcopy(seal);edit(value);reseal(doc,value)
            malformed.append({'case':label,'results':rejected(doc)})
        malformed_case('wrong_schema',lambda s:s.update(schema='old-local-seal'))
        malformed_case('wrong_id',lambda s:s.update(id=p.ORDER[1]))
        malformed_case('files_wrong_type',lambda s:s.update(files=[]))
        malformed_case('required_row_removed',lambda s:s['files'].pop(rid+'/receipt.json'))
        for path in ('/escape.json','../escape.json','groups/r5-'+rid+'/../escape.json',
                     'groups//r5-'+rid+'/extra.json','groups\\r5-'+rid+'\\extra.json',
                     'groups/r5-'+rid+'/stdout.log','groups/r5-'+p.ORDER[1]+'/extra.json'):
            malformed_case('path_boundary:'+path,lambda s,path=path:s['files'].update({path:'a'*64}))
        for h in (None,23,'G'*64,'a'*63):
            malformed_case('digest_format:'+repr(h),lambda s,h=h:s['files'].update({rid+'/receipt.json':h}))
        # Local log metadata is expressly informational, not a portable payload.
        doc=copy.deepcopy(artifact);value=copy.deepcopy(seal);value.pop('local_only_file_digests');reseal(doc,value);save(doc)
        c.sealed(upload,collector.read_bytes,[rid])
        optional_result=collector.collect([upload],request)
        assert next(row for row in optional_result['rows'] if row['id']==rid)['outcome']=='RECORDED'
        save(artifact)
        assert collector.read_bytes(upload/rid/'receipt.json')==prefix
        dump('PORTABLE-PROBE.json',{'status':'PASS','control':P['control'],'fixture':'test_r5.PortablePrefixTests.make_pair',
            'pipeline':'real _run_group/root_outcome/finalize/fallback/pack/read_bytes/sealed/public collect',
            'external_execution_and_sampling':'SYNTHETIC_ONLY',
            'producer_directory_deleted':True,'upload_only_files':[pack_evidence.NAME],
            'packed_state':artifact['state'],'prefix_sha256':sha(prefix),'prefix_byte_exact':True,
            'completed_root':rid,'completed_outcome':rows[rid]['outcome'],'completed_expected_match':rows[rid]['r5_expected_match'],
            'later_failed_root':p.ORDER[1],'later_outcome':rows[p.ORDER[1]]['outcome'],
            'unstarted_and_deferred':'UNKNOWN/NOT_RUN or DEFERRED_NOT_SELECTED',
            'raw_log_payloads_uploaded':False,'local_digest_metadata_optional':True,
            'structured_sealed_members':members,'member_negatives':negatives,'malformed_seals':malformed,
            'member_negative_count':len(negatives),'malformed_seal_count':len(malformed),
            'elapsed_seconds':(time.monotonic_ns()-start)/1e9,'full_inventory_complete':False,'proof_credit':'NONE'})
        print('PORTABLE_PROBE_PASS',len(members),'sealed members;',len(negatives),'member negatives;',len(malformed),'malformed seals')

if __name__=='__main__':main()
